function Append-Log([string]$t) { $log.AppendText($t + "`r`n") }

function Refresh-View {
    $grid.Rows.Clear()
    $installs = @(Get-DiscordInstalls)
    if ($installs.Count -eq 0) {
        [void]$grid.Rows.Add('未检测到 Discord', '请先安装 Discord 桌面版')
        $btnInstall.Enabled = $false
        $btnUninstall.Enabled = $false
    } else {
        foreach ($i in $installs) {
            if ($i.Injected) { $status = '已注入' }
            elseif ($i.OtherMod) { $status = '被其他 mod 占用（跳过）' }
            else { $status = '未注入' }
            [void]$grid.Rows.Add(($i.Flavor + '  ' + $i.Version), $status)
        }
        $btnInstall.Enabled = $true
        $btnUninstall.Enabled = $true
    }
    $lblDiag.Text = Get-Diagnostics
}

function Start-Worker([string]$action) {
    $close = $false; $relaunch = $false
    if (Get-DiscordProcesses) {
        $msg = "Discord 正在运行，需要关闭后重启才能生效。`n`n是 = 关闭 Discord 并在完成后自动重启`n否 = 只写入文件（下次你自己重启 Discord 生效）`n取消 = 不操作"
        $r = [System.Windows.Forms.MessageBox]::Show($msg, 'Halcyon', [System.Windows.Forms.MessageBoxButtons]::YesNoCancel, [System.Windows.Forms.MessageBoxIcon]::Question)
        if ($r -eq [System.Windows.Forms.DialogResult]::Cancel) { return }
        if ($r -eq [System.Windows.Forms.DialogResult]::Yes) { $close = $true; $relaunch = $true }
    }
    $Sync.Action = $action
    $Sync.Force = $false
    $Sync.CloseDiscord = $close
    $Sync.Relaunch = $relaunch
    $Sync.KeepInjected = $chkKeep.Checked
    $Sync.SelfPath = (Get-SelfPath)
    $Sync.Done = $false
    $Sync.Ok = $false
    $Sync.Summary = ''
    while ($Sync.Log.Count -gt 0) { [void]$Sync.Log.Dequeue() }
    $log.Clear()
    $btnInstall.Enabled = $false
    $btnUninstall.Enabled = $false
    $bar.Visible = $true
    $script:rs = [runspacefactory]::CreateRunspace()
    $script:rs.ApartmentState = 'STA'
    $script:rs.ThreadOptions = 'ReuseThread'
    $script:rs.Open()
    $script:rs.SessionStateProxy.SetVariable('Sync', $Sync)
    $script:psw = [powershell]::Create()
    $script:psw.Runspace = $script:rs
    [void]$script:psw.AddScript($Engine.ToString() + "`r`n" + $Worker.ToString())
    $script:handle = $script:psw.BeginInvoke()
    $timer.Start()
}
$timer.Add_Tick({
    while ($Sync.Log.Count -gt 0) { Append-Log ([string]$Sync.Log.Dequeue()) }
    if ($Sync.Done) {
        $timer.Stop()
        try { $script:psw.EndInvoke($script:handle) } catch {}
        try { $script:psw.Dispose() } catch {}
        try { $script:rs.Close(); $script:rs.Dispose() } catch {}
        $script:psw = $null; $script:rs = $null
        while ($Sync.Log.Count -gt 0) { Append-Log ([string]$Sync.Log.Dequeue()) }
        $bar.Visible = $false
        Refresh-View
        if ($Sync.Summary) {
            Append-Log $Sync.Summary
            if ($Sync.Ok) { $icon = [System.Windows.Forms.MessageBoxIcon]::Information }
            else { $icon = [System.Windows.Forms.MessageBoxIcon]::Error }
            [void][System.Windows.Forms.MessageBox]::Show($Sync.Summary, 'Halcyon', [System.Windows.Forms.MessageBoxButtons]::OK, $icon)
        }
    }
})

$btnInstall.Add_Click({ Start-Worker 'install' })
$btnUninstall.Add_Click({ Start-Worker 'uninstall' })

$form.Add_FormClosing({
    try { if ($script:psw) { $script:psw.Stop(); $script:psw.Dispose() } } catch {}
    try { if ($script:rs) { $script:rs.Close(); $script:rs.Dispose() } } catch {}
})

Refresh-View
