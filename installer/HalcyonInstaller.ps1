// Generated by Halcyon. Do not edit; run the installer's Uninstall to remove.
"use strict";

const fs = require("fs");
const path = require("path");
const os = require("os");
const { webFrame } = require("electron");

// Discord's own preload path — chained AFTER we start the payload (below).
const original = process.env.HALCYON_ORIGINAL_PRELOAD;

// 2. Load the payload. Prefer the auto-updated cache (refreshed by the main
//    process each launch); fall back to the copy shipped next to this shim so a
//    first run with no network still works. Reading a local file keeps startup
//    instant and offline-safe — the page itself never fetches (Discord's CSP
//    would block a cross-origin fetch anyway).
function cacheFile() {
  const base =
    process.env.APPDATA ||
    (process.platform === "darwin"
      ? path.join(os.homedir(), "Library", "Application Support")
      : process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"));
  return path.join(base, "Halcyon", "halcyon.js");
}

function readPayload() {
  const candidates = [cacheFile(), path.join(__dirname, "halcyon.js")];
  for (const p of candidates) {
    try {
      const code = fs.readFileSync(p, "utf8");
      if (code && code.length > 1024) return code;
    } catch (err) {
      // try the next candidate
    }
  }
  return null;
}

function inject() {
  const code = readPayload();
  if (!code) {
    console.error("[Halcyon] no payload available (cache empty, no bundled copy)");
    return;
  }
  // Run the payload in the page's MAIN world via webFrame.executeJavaScript. It
  // executes at document-start (before Discord's bundle, so Halcyon wins the
  // Webpack race) and is NOT subject to Discord's CSP — so, unlike a <script>
  // tag, no CSP stripping is needed. This is how Vencord/Equicord run their
  // renderer, and it avoids the CSP/Proxy tricks that broke the window controls.
  try {
    webFrame.executeJavaScript(code + "\n//# sourceURL=halcyon://payload");
  } catch (err) {
    console.error("[Halcyon] executeJavaScript failed:", err);
  }
}

inject();

// Now chain Discord's own preload so nothing it sets up is lost.
if (original) {
  try {
    require(original);
  } catch (err) {
    console.error("[Halcyon] Discord preload failed:", err);
  }
}
'@
    function Write-Utf8NoBom {
        param([Parameter(Mandatory)][string]$Path, [Parameter(Mandatory)][string]$Content)
        $enc = New-Object System.Text.UTF8Encoding($false)
        [System.IO.File]::WriteAllText($Path, $Content, $enc)
    }

    function Test-Injected {
        # Our injection: resources/app.asar is a DIRECTORY whose index.js carries
        # the marker; the original app is preserved next to it as _app.asar.
        param([Parameter(Mandatory)][string]$ResourcesPath)
        $idx = Join-Path (Join-Path $ResourcesPath 'app.asar') 'index.js'
        if (-not (Test-Path -LiteralPath $idx)) { return $false }
        try {
            $head = Get-Content -LiteralPath $idx -TotalCount 3 -ErrorAction Stop
            return (($head -join "`n").Contains($script:Marker))
        } catch { return $false }
    }

    function Test-ForeignShim {
        # app.asar replaced by a directory that is NOT ours (Vencord/Equicord/BD).
        param([Parameter(Mandatory)][string]$ResourcesPath)
        $asar = Join-Path $ResourcesPath 'app.asar'
        $isDir = $false
        try { $ai = Get-Item -LiteralPath $asar -ErrorAction SilentlyContinue; if ($ai -and $ai.PSIsContainer) { $isDir = $true } } catch {}
        if (-not $isDir) { return $false }
        return (-not (Test-Injected -ResourcesPath $ResourcesPath))
    }

    function Get-DiscordInstalls {
        $result = @()
        $root = $env:LOCALAPPDATA
        foreach ($flavor in $script:Flavors) {
            $base = Join-Path $root $flavor
            if (-not (Test-Path -LiteralPath $base)) { continue }
            $best = $null; $bestVer = $null
            Get-ChildItem -LiteralPath $base -Directory -Filter 'app-*' -ErrorAction SilentlyContinue | ForEach-Object {
                $v = $null
                if ([version]::TryParse($_.Name.Substring(4), [ref]$v)) {
                    if ($null -eq $bestVer -or $v -gt $bestVer) { $bestVer = $v; $best = $_ }
                }
            }
            if ($null -eq $best) { continue }
            $resources = Join-Path $best.FullName 'resources'
            $asar = Join-Path $resources 'app.asar'
            $orig = Join-Path $resources '_app.asar'
            # Valid install: has app.asar (vanilla file OR a mod's directory) or our _app.asar.
            if (-not (Test-Path -LiteralPath $asar) -and -not (Test-Path -LiteralPath $orig)) { continue }
            $result += [pscustomobject]@{
                Flavor        = $flavor
                Version       = $bestVer.ToString()
                ResourcesPath = $resources
                Injected      = (Test-Injected -ResourcesPath $resources)
                OtherMod      = (Test-ForeignShim -ResourcesPath $resources)
            }
        }
        return ,$result
    }
    function Update-PayloadCache {
        # Download the latest payload into the per-user cache (atomic). $true on success.
        try {
            if (-not (Test-Path -LiteralPath $script:AppDataHalcyon)) {
                New-Item -ItemType Directory -Path $script:AppDataHalcyon -Force | Out-Null
            }
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
            $wc = New-Object System.Net.WebClient
            $wc.Headers.Add('User-Agent', 'Halcyon-Installer')
            $bytes = $wc.DownloadData($script:PayloadUrl)
            $wc.Dispose()
            if ($null -eq $bytes -or $bytes.Length -lt 1024) { return $false }
            $tmp = $script:CacheFile + '.download.tmp'
            [System.IO.File]::WriteAllBytes($tmp, $bytes)
            if (Test-Path -LiteralPath $script:CacheFile) {
                [System.IO.File]::Replace($tmp, $script:CacheFile, $null)  # atomic replace
            } else {
                [System.IO.File]::Move($tmp, $script:CacheFile)
            }
            return $true
        } catch { return $false }
    }

    function Install-One {
        param([Parameter(Mandatory)]$Install, [switch]$Force)
        $res  = $Install.ResourcesPath
        $asar = Join-Path $res 'app.asar'
        $orig = Join-Path $res '_app.asar'
        if ((Test-ForeignShim -ResourcesPath $res) -and (-not $Force)) { return 'skipped-foreign' }
        $already = Test-Injected -ResourcesPath $res
        # Preserve the real app exactly once (rename app.asar -> _app.asar).
        if (-not (Test-Path -LiteralPath $orig)) {
            $ai = Get-Item -LiteralPath $asar -ErrorAction SilentlyContinue
            if ($ai -and -not $ai.PSIsContainer) { Move-Item -LiteralPath $asar -Destination $orig }
            else { return 'error: app.asar missing' }
        } else {
            # A stale app.asar file beside _app.asar — the real app is already saved.
            $ai = Get-Item -LiteralPath $asar -ErrorAction SilentlyContinue
            if ($ai -and -not $ai.PSIsContainer) { Remove-Item -LiteralPath $asar -Force }
        }
        if (-not (Test-Path -LiteralPath $asar)) { New-Item -ItemType Directory -Path $asar -Force | Out-Null }
        Write-Utf8NoBom -Path (Join-Path $asar 'package.json') -Content $script:ShimPackageJson
        Write-Utf8NoBom -Path (Join-Path $asar 'index.js')     -Content $script:ShimIndexJs
        Write-Utf8NoBom -Path (Join-Path $asar 'preload.js')   -Content $script:ShimPreloadJs
        if (Test-Path -LiteralPath $script:CacheFile) {
            try { [System.IO.File]::Copy($script:CacheFile, (Join-Path $asar 'halcyon.js'), $true) } catch {}
        }
        if ($already) { return 'updated' } else { return 'installed' }
    }

    function Uninstall-One {
        param([Parameter(Mandatory)]$Install)
        $res  = $Install.ResourcesPath
        $asar = Join-Path $res 'app.asar'
        $orig = Join-Path $res '_app.asar'
        if (-not (Test-Injected -ResourcesPath $res)) {
            if (Test-ForeignShim -ResourcesPath $res) { return 'left-foreign' }
            return 'not-present'
        }
        try {
            Remove-Item -LiteralPath $asar -Recurse -Force -ErrorAction Stop
            if (Test-Path -LiteralPath $orig) { Move-Item -LiteralPath $orig -Destination $asar }
            return 'removed'
        } catch { return ('error: ' + $_.Exception.Message) }
    }
    function Get-DiscordProcesses {
        Get-Process -ErrorAction SilentlyContinue | Where-Object { $script:ProcNames -contains $_.Name }
    }

    function Stop-DiscordProcesses {
        foreach ($p in (Get-DiscordProcesses)) { try { $p.Kill() } catch {} }
        for ($i = 0; $i -lt 25 -and (Get-DiscordProcesses); $i++) { Start-Sleep -Milliseconds 200 }
    }

    function Start-Discord {
        param([string]$Flavor = 'Discord')
        try {
            $update = Join-Path (Join-Path $env:LOCALAPPDATA $Flavor) 'Update.exe'
            if (Test-Path -LiteralPath $update) {
                Start-Process -FilePath $update -ArgumentList @('--processStart', ($Flavor + '.exe'))
            }
        } catch {}
    }

    function Get-SelfPath {
        # $PSCommandPath is populated when run as a .ps1 (dev); EMPTY inside a ps2exe
        # .exe, where the running module's file name is the exe we want to relaunch.
        if ($PSCommandPath) { return $PSCommandPath }
        try { return [System.Diagnostics.Process]::GetCurrentProcess().MainModule.FileName } catch { return $null }
    }

    function Copy-SelfToStable {
        # The re-inject task must point at a STABLE path: a portable exe run from
        # Downloads can be moved/deleted, which would silently break re-injection.
        # Copy ourselves into %LOCALAPPDATA%\Halcyon and register that copy instead.
        param([Parameter(Mandatory)][string]$SelfPath)
        try {
            $dir = Join-Path $env:LOCALAPPDATA 'Halcyon'
            if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
            $dest = Join-Path $dir (Split-Path -Leaf $SelfPath)
            if ([System.IO.Path]::GetFullPath($SelfPath) -ne [System.IO.Path]::GetFullPath($dest)) {
                [System.IO.File]::Copy($SelfPath, $dest, $true)
            }
            return $dest
        } catch { return $SelfPath }
    }

    function Register-KeepInjected {
        param([Parameter(Mandatory)][string]$SelfPath)
        $isExe = $SelfPath -match '\.exe$'
        if ($isExe) {
            $prog = $SelfPath; $argStr = '-EnsureInjected'
            $runCmd = '"' + $SelfPath + '" -EnsureInjected'
        } else {
            $prog = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
            $argStr = '-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "' + $SelfPath + '" -EnsureInjected'
            $runCmd = '"' + $prog + '" ' + $argStr
        }
        try {
            $action  = New-ScheduledTaskAction -Execute $prog -Argument $argStr
            $trigger = New-ScheduledTaskTrigger -AtLogOn
            try {
                $rep = (New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 30)).Repetition
                $trigger.Repetition = $rep
            } catch {}
            $settings  = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
            $principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited
            Register-ScheduledTask -TaskName $script:TaskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force -ErrorAction Stop | Out-Null
            return 'scheduled-task'
        } catch {
            try {
                New-ItemProperty -LiteralPath 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run' -Name $script:TaskName -Value $runCmd -PropertyType String -Force | Out-Null
                return 'run-key'
            } catch { return 'failed' }
        }
    }
    function Unregister-KeepInjected {
        try { Unregister-ScheduledTask -TaskName $script:TaskName -Confirm:$false -ErrorAction SilentlyContinue | Out-Null } catch {}
        try {
            $runKey = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'
            if (Get-ItemProperty -LiteralPath $runKey -Name $script:TaskName -ErrorAction SilentlyContinue) {
                Remove-ItemProperty -LiteralPath $runKey -Name $script:TaskName -ErrorAction SilentlyContinue
            }
        } catch {}
    }

    function Invoke-EnsureInjected {
        # Silent, idempotent — for the logon task. Never kills or launches Discord.
        if (-not (Test-Path -LiteralPath $script:CacheFile)) { Update-PayloadCache | Out-Null }
        foreach ($i in (Get-DiscordInstalls)) {
            if (-not $i.Injected) { Install-One -Install $i | Out-Null }
        }
    }

    function Get-Diagnostics {
        $installs = @(Get-DiscordInstalls)
        $node = Get-Command node -ErrorAction SilentlyContinue
        if ($node) { $nodeStr = 'found (' + $node.Source + ')' } else { $nodeStr = 'not found - not required' }
        if (Test-Path -LiteralPath $script:CacheFile) {
            $kb = [math]::Round(((Get-Item -LiteralPath $script:CacheFile).Length / 1KB))
            $cacheStr = ('' + $kb + ' KB')
        } else { $cacheStr = 'none yet' }
        return ('Discord: ' + $installs.Count + '  |  PowerShell ' + $PSVersionTable.PSVersion.ToString() + '  |  Node: ' + $nodeStr + '  |  cache: ' + $cacheStr)
    }
}

# ============================================================================
#  Worker — runs inside the background runspace. Uses engine functions + $Sync.
#  (Never touches WinForms controls — the UI drains $Sync.Log on its own thread.)
# ============================================================================
$Worker = {
    function Log($m) { $Sync.Log.Enqueue([string]$m) }
    try {
        if ($Sync.Action -eq 'install') {
            $running = @()
            if ($Sync.CloseDiscord) {
                $running = @(Get-DiscordProcesses | ForEach-Object { $_.Name } | Select-Object -Unique)
                Log '正在关闭 Discord...'; Stop-DiscordProcesses
            }
            Log '正在从 GitHub 获取最新插件...'
            if (Update-PayloadCache) { Log '  插件已缓存' } else { Log '  下载失败，将使用已有缓存 / 内置副本' }
            $n = 0
            foreach ($i in (Get-DiscordInstalls)) {
                $r = Install-One -Install $i -Force:$Sync.Force
                Log ('  ' + $i.Flavor + ' ' + $i.Version + ' -> ' + $r)
                if ($r -eq 'installed' -or $r -eq 'updated') { $n++ }
            }
            if ($Sync.KeepInjected) {
                $stable = Copy-SelfToStable -SelfPath $Sync.SelfPath
                Log ('开机自动保持注入: ' + (Register-KeepInjected -SelfPath $stable))
            } else { Unregister-KeepInjected; Log '已关闭开机自动保持注入' }
            if ($Sync.CloseDiscord -and $Sync.Relaunch) {
                Log '正在重新启动 Discord...'
                if (-not $running) { $running = @('Discord') }
                foreach ($fl in $running) { Start-Discord -Flavor $fl }
            }
            $Sync.Ok = $true
            $Sync.Summary = ('完成：已注入 / 更新 ' + $n + ' 个 Discord。重启 Discord 后按 Ctrl+Shift+H 打开设置。')
        }
        elseif ($Sync.Action -eq 'uninstall') {
            $running = @()
            if ($Sync.CloseDiscord) {
                $running = @(Get-DiscordProcesses | ForEach-Object { $_.Name } | Select-Object -Unique)
                Log '正在关闭 Discord...'; Stop-DiscordProcesses
            }
            $n = 0
            foreach ($i in (Get-DiscordInstalls)) {
                $r = Uninstall-One -Install $i
                Log ('  ' + $i.Flavor + ' -> ' + $r)
                if ($r -eq 'removed') { $n++ }
            }
            Unregister-KeepInjected
            foreach ($d in @($script:AppDataHalcyon, (Join-Path $env:LOCALAPPDATA 'Halcyon'))) {
                try { if (Test-Path -LiteralPath $d) { Remove-Item -LiteralPath $d -Recurse -Force -ErrorAction SilentlyContinue } } catch {}
            }
            if ($Sync.CloseDiscord -and $Sync.Relaunch) {
                Log '正在重新启动 Discord...'
                if (-not $running) { $running = @('Discord') }
                foreach ($fl in $running) { Start-Discord -Flavor $fl }
            }
            $Sync.Ok = $true
            $Sync.Summary = ('完成：已卸载 ' + $n + ' 个。Discord 已恢复原版。')
        }
    } catch {
        $Sync.Ok = $false
        $Sync.Summary = ('出错：' + $_.Exception.Message)
        Log ('ERROR: ' + $_.Exception.Message)
    } finally {
        $Sync.Done = $true
    }
}
